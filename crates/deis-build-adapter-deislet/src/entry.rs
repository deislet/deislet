//! The entry module: the bridge between deis-runtime and an edge-canon
//! handler.
//!
//! deis-runtime loads one ESM module per app, keeps its default export, and
//! calls it once per request with a context it builds itself
//! (`crates/deis-runtime/src/runtime/js/runtime.js`). That context carries
//! `request`, `env`, `services` and `waitUntil`, and nothing about *which*
//! handler should run - the runtime has no idea an app has more than one.
//!
//! So the module generated here is what makes a file tree behave like an app:
//! it picks the handler whose pattern fits the path, fills in the placeholder
//! values, adds the convenience fields edge-canon promises (`path`, `method`,
//! `query`, `cookies`, `log`) on top of what the runtime supplied, and answers
//! 404 when nothing matched.
//!
//! It fills `context.params` itself rather than trusting the runtime's copy,
//! and the reason is not that the runtime matches less than this module does.
//! The runtime understands the same three kinds of segment, catch-all
//! included, and ranks competing patterns by the same rule
//! (`deis_bundle::routing`). What it cannot do is name a catch-all: a manifest
//! pattern keeps only the `*`, so `params['*']` is the one key the runtime can
//! promise, while `functions/api/[[catch]].ts` says the handler expects to
//! read the tail as `params.catch` as well. This module still has the file
//! name, so it publishes the capture under both spellings - and it has to
//! build a context anyway for `path`, `method`, `query`, `cookies` and `log`,
//! which the runtime does not supply at all. So it rebuilds `params` with the
//! rest rather than merging into a half-filled copy.

use crate::routing::RoutePlan;

/// The banner at the top of every generated entry module.
const HEADER: &str = r#"/**
 * Deislet entry point
 * Generated by deis-build; edits are lost on the next build.
 *
 * deis-runtime imports this module, keeps its default export and calls it once
 * per request with the context it built. Everything below is what turns that
 * single call into the routes the file tree describes.
 *
 * Bundle format: docs/implementation-plan.zh.md section 2.
 */

"#;

/// JavaScript, verbatim, that every generated entry module carries.
///
/// Kept out of the formatting path deliberately: this is the half that is the
/// same for every app, and inlining it into a `format!` would mean escaping
/// every brace in it, which is how a generated-code bug gets written.
const RUNTIME_SUPPORT: &str = r#"
// Match one pattern against the request's path segments.
//
// Returns the placeholder values on a match and null otherwise. Both sides are
// percent-decoded before they are compared, so a literal segment with a space
// or a non-ASCII character - which the browser always sends escaped - can still
// match the pattern it was written as.
function matchRoute(route, segments) {
  const params = {};
  const pattern = route.segments;

  for (let i = 0; i < pattern.length; i++) {
    const part = pattern[i];

    if (part === '*') {
      // A catch-all stands for the whole remainder, including none of it.
      const rest = segments.slice(i).map(decodeSegment).join('/');
      params['*'] = rest;
      if (route.wildcard) params[route.wildcard] = rest;
      return params;
    }

    if (i >= segments.length) return null;

    if (part.charAt(0) === ':') {
      params[part.slice(1)] = decodeSegment(segments[i]);
      continue;
    }

    if (decodeSegment(part) !== decodeSegment(segments[i])) return null;
  }

  return pattern.length === segments.length ? params : null;
}

function decodeSegment(segment) {
  try {
    return decodeURIComponent(segment);
  } catch (_) {
    // A malformed escape is not worth failing a request over; compare it
    // as the raw bytes the client sent.
    return segment;
  }
}

function splitPath(pathname) {
  const parts = [];
  for (const part of pathname.split('/')) {
    if (part !== '') parts.push(part);
  }
  return parts;
}

// The query string, parsed here rather than through URLSearchParams: the
// runtime's polyfill of it exposes only `get`, so iterating it would throw on
// exactly the platform this module is built for.
function parseQuery(search) {
  const query = {};
  if (!search) return query;

  for (const pair of search.replace(/^\?/, '').split('&')) {
    if (pair === '') continue;
    const eq = pair.indexOf('=');
    const rawKey = eq === -1 ? pair : pair.slice(0, eq);
    const rawValue = eq === -1 ? '' : pair.slice(eq + 1);
    const key = decodeSegment(rawKey.replace(/\+/g, ' '));
    const value = decodeSegment(rawValue.replace(/\+/g, ' '));

    if (Object.prototype.hasOwnProperty.call(query, key)) {
      const existing = query[key];
      if (Array.isArray(existing)) existing.push(value);
      else query[key] = [existing, value];
    } else {
      query[key] = value;
    }
  }

  return query;
}

function parseCookies(request) {
  const jar = {};
  const header = request && request.headers ? request.headers.get('Cookie') : null;

  if (header) {
    for (const cookie of header.split(';')) {
      const eq = cookie.indexOf('=');
      if (eq === -1) continue;
      jar[cookie.slice(0, eq).trim()] = cookie.slice(eq + 1).trim();
    }
  }

  return {
    get(name) { return jar[name]; },
    getAll() { return Object.assign({}, jar); },
  };
}

function pathnameOf(request) {
  const raw = request && request.url ? String(request.url) : '/';
  try {
    return new URL(raw).pathname;
  } catch (_) {
    // A relative URL, which the URL polyfill accepts but a real URL does not.
    const withoutQuery = raw.split('?')[0].split('#')[0];
    return withoutQuery.startsWith('/') ? withoutQuery : '/' + withoutQuery;
  }
}

// The context the handler sees: everything deis-runtime supplied - env,
// services, waitUntil - plus the request-shaped conveniences edge-canon
// promises. `params` is overwritten with this module's own match: it is the
// only one that also knows the name the catch-all was written with in the
// file tree, so `params.catch` works alongside `params['*']`.
function buildContext(context, params, pathname) {
  const request = context.request;
  const search = request && request.url ? String(request.url).split('?')[1] : '';

  return Object.assign({}, context, {
    params: params,
    path: pathname,
    method: request ? request.method : 'GET',
    query: parseQuery(search ? '?' + search.split('#')[0] : ''),
    headers: request ? request.headers : undefined,
    cookies: parseCookies(request),
    log: {
      debug: (...args) => console.debug(...args),
      info: (...args) => console.info(...args),
      warn: (...args) => console.warn(...args),
      error: (...args) => console.error(...args),
    },
  });
}

export default async function deisletEntry(context) {
  const pathname = pathnameOf(context.request);
  const segments = splitPath(pathname);

  for (const route of ROUTES) {
    const params = matchRoute(route, segments);
    if (params === null) continue;
    return await route.handler(buildContext(context, params, pathname));
  }

  // No handler claims this path. An app with static files never gets here for
  // them: deis-runtime serves a bundle asset before it starts an isolate.
  return new Response('Not Found', {
    status: 404,
    headers: { 'content-type': 'text/plain; charset=utf-8' },
  });
}
"#;

/// Generate the entry module for a route plan.
pub fn generate_entry_module(plan: &RoutePlan) -> String {
    let routes = &plan.routes;
    let mut code = String::new();

    code.push_str(HEADER);

    for (index, route) in routes.iter().enumerate() {
        code.push_str(&format!(
            "import handler{index} from {};\n",
            js_string(&route.import_path)
        ));
    }

    if routes.is_empty() {
        // An app with no handlers is legal - a site that is only static files
        // - and must still load, so the table is simply empty.
        code.push_str("// This app declares no function routes.\n");
    }

    code.push_str(concat!(
        "\n// Ordered most-specific first, by the rule deis-runtime applies to\n",
        "// the same patterns (deis_bundle::routing): the first one that fits wins.\n",
        "const ROUTES = [\n",
    ));
    for (index, route) in routes.iter().enumerate() {
        let segments: Vec<&str> = route.pattern.split('/').filter(|s| !s.is_empty()).collect();
        code.push_str(&format!(
            "  {{ pattern: {}, segments: {}, wildcard: {}, handler: handler{index} }},\n",
            js_string(&route.pattern),
            serde_json::to_string(&segments).expect("route segments serialise"),
            match &route.wildcard {
                Some(name) => js_string(name),
                None => "null".to_string(),
            },
        ));
    }
    code.push_str("];\n");

    code.push_str(RUNTIME_SUPPORT);

    // The platform-called handlers. They are named exports because that is
    // what deis-runtime reads off the module (`mod.queue` becomes
    // `user_module.queue`); an app that declares a queue in its manifest and
    // exports nothing here has its whole batch handed back and eventually
    // dead-lettered, which is why the build says so.
    if let Some(import) = &plan.queue {
        code.push_str(&format!(
            "\n// Queue consumer: deis-runtime calls this with a whole batch.\nimport \
             queueHandler from {};\nexport const queue = queueHandler;\n",
            js_string(import)
        ));
    }
    if let Some(import) = &plan.scheduled {
        code.push_str(&format!(
            "\n// Cron handler: the control plane triggers this on schedule.\nimport \
             scheduledHandler from {};\nexport const scheduled = scheduledHandler;\n",
            js_string(import)
        ));
    }

    code
}

/// A JavaScript string literal, escaped by the JSON encoder rather than by
/// hand: a path with a quote or a backslash in it would otherwise generate a
/// module that does not parse.
fn js_string(value: &str) -> String {
    serde_json::to_string(value).expect("a string always serialises")
}

#[cfg(test)]
mod tests {
    use super::*;

    use crate::routing::RouteEntry;

    fn entry(pattern: &str, import: &str, wildcard: Option<&str>) -> RouteEntry {
        RouteEntry {
            pattern: pattern.to_string(),
            import_path: import.to_string(),
            wildcard: wildcard.map(|w| w.to_string()),
        }
    }

    fn plan(routes: &[RouteEntry]) -> RoutePlan {
        RoutePlan {
            routes: routes.to_vec(),
            ..Default::default()
        }
    }

    #[test]
    fn the_module_exports_the_default_the_runtime_looks_for() {
        // runtime.js: "No default export handler found" unless this holds.
        let code = generate_entry_module(&plan(&[entry("/", "../src/index.ts", None)]));
        assert!(code.contains("export default async function deisletEntry(context)"));
    }

    #[test]
    fn every_handler_is_imported_and_placed_in_the_table() {
        let code = generate_entry_module(&plan(&[
            entry("/", "../src/index.ts", None),
            entry("/users/:id", "../src/users/[id].ts", None),
        ]));
        assert!(code.contains("import handler0 from \"../src/index.ts\";"));
        assert!(code.contains("import handler1 from \"../src/users/[id].ts\";"));
        assert!(code.contains(r#"segments: ["users",":id"], wildcard: null, handler: handler1"#));
    }

    #[test]
    fn a_catch_all_carries_the_name_the_handler_reads_it_by() {
        let code = generate_entry_module(&plan(&[entry(
            "/api/*",
            "../src/api/[[catch]].ts",
            Some("catch"),
        )]));
        assert!(code.contains(r#"segments: ["api","*"], wildcard: "catch""#));
    }

    #[test]
    fn an_app_with_no_handlers_still_produces_a_loadable_module() {
        // A static-only site has no functions; the module must still evaluate,
        // or the whole app fails to load rather than serving its files.
        let code = generate_entry_module(&plan(&[]));
        assert!(code.contains("const ROUTES = [\n];"));
        assert!(code.contains("export default"));
        assert!(!code.contains("import handler"));
    }

    #[test]
    fn a_path_with_a_quote_in_it_cannot_break_out_of_the_import() {
        let code = generate_entry_module(&plan(&[entry("/x", "../src/we\"ird.ts", None)]));
        assert!(code.contains(r#"import handler0 from "../src/we\"ird.ts";"#));
    }

    #[test]
    fn a_queue_handler_is_re_exported_under_the_name_the_runtime_reads() {
        // deis-runtime picks up `mod.queue` and nothing else; an app whose
        // manifest declares a queue but exports no handler has every batch
        // handed back and eventually dead-lettered.
        let code = generate_entry_module(&RoutePlan {
            routes: vec![entry("/", "../src/index.ts", None)],
            queue: Some("../src/_queue.ts".to_string()),
            ..Default::default()
        });
        assert!(code.contains("import queueHandler from \"../src/_queue.ts\";"));
        assert!(code.contains("export const queue = queueHandler;"));
    }

    #[test]
    fn a_scheduled_handler_is_re_exported_too() {
        let code = generate_entry_module(&RoutePlan {
            routes: Vec::new(),
            scheduled: Some("../src/_scheduled.ts".to_string()),
            ..Default::default()
        });
        assert!(code.contains("export const scheduled = scheduledHandler;"));
    }

    #[test]
    fn an_app_without_those_handlers_exports_neither() {
        let code = generate_entry_module(&plan(&[entry("/", "../src/index.ts", None)]));
        assert!(!code.contains("export const queue"));
        assert!(!code.contains("export const scheduled"));
    }

    #[test]
    fn the_module_does_not_iterate_url_search_params() {
        // The runtime's URLSearchParams polyfill has only `get`; iterating it
        // throws at request time, which is the worst place to find out.
        let code = generate_entry_module(&plan(&[entry("/", "../src/index.ts", None)]));
        assert!(!code.contains("Object.fromEntries("));
        assert!(!code.contains("searchParams"));
    }
}
