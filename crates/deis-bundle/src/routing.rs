//! The one rule that decides which route pattern answers a request.
//!
//! Two places in the platform have to answer "of the patterns that fit this
//! path, which one wins?":
//!
//!   - **deis-build**, at build time, when it orders the table it bakes into
//!     the generated entry module. That table is tried top to bottom, so the
//!     order *is* the decision, and it is also the order the manifest lists
//!     the routes in.
//!   - **deis-runtime**, at request time, when it fills `context.params` for
//!     an app loaded as a bare module and when anything else asks which of the
//!     manifest's patterns a path belongs to.
//!
//! They used to answer it with two different rules, and two rules is not a
//! style problem. A project with `functions/[org]/settings.ts` (`/:org/
//! settings`) and `functions/admin/[page].ts` (`/admin/:page`) has one path,
//! `/admin/settings`, that both patterns fit. Whichever rule the entry module
//! was built with picks the handler that actually runs; whichever rule the
//! runtime uses picks the params and the route the manifest implies. When the
//! two disagree the symptom is a handler that is never called, with no error
//! anywhere - so the rule lives here, in the crate both sides already depend
//! on. A second implementation of it, even one that happens to agree today, is
//! itself the defect; the disagreement it grows into only shows up later.
//!
//! The rule, smallest key first (see [`Specificity`]):
//!
//!   1. a pattern with no catch-all beats one with a catch-all;
//!   2. otherwise the first segment where the two differ decides: literal
//!      beats placeholder beats catch-all;
//!   3. a longer pattern beats a shorter one it agrees with as far as it goes;
//!   4. anything still tied is settled by the caller's `order`.

/// The pattern segment standing for "everything that is left".
///
/// `deis-build` emits it for an edge-canon `[[name]]` file: `functions/api/
/// [[catch]].ts` becomes the pattern `/api/*`.
pub const CATCH_ALL_SEGMENT: &str = "*";

/// The `context.params` key a catch-all capture is stored under.
///
/// A manifest pattern keeps only the `*`, not the file's `[[catch]]` name, so
/// this is the one key any reader of the manifest can promise. The entry
/// module generated by `deis-build` knows the file name too and publishes the
/// same capture under both spellings.
pub const CATCH_ALL_PARAM: &str = "*";

/// The character a `:name` placeholder segment starts with.
pub const PLACEHOLDER_PREFIX: char = ':';

/// How tightly one pattern segment constrains the path segment it matched.
///
/// The numbers only matter relative to each other: a literal pins the segment
/// to one value, a placeholder accepts any single segment, and a catch-all
/// accepts any number of them.
const RANK_LITERAL: u8 = 2;
const RANK_PLACEHOLDER: u8 = 1;
const RANK_CATCH_ALL: u8 = 0;

/// Split a route pattern or a request path into its non-empty segments.
///
/// Leading, trailing and repeated slashes collapse away, so `/users/1` and
/// `/users/1/` split the same way and trailing-slash insensitivity comes for
/// free.
pub fn segments(path: &str) -> Vec<&str> {
    path.split('/')
        .filter(|segment| !segment.is_empty())
        .collect()
}

/// The ordering key that decides which of two matching patterns wins.
///
/// Smaller is more specific, so a sorted table is tried front to back and the
/// minimum key among the matching patterns is the same handler either way.
///
/// `order` breaks a tie between two patterns the shape rule cannot separate -
/// `/:org/settings` and `/:user/settings` are the same shape and both match
/// `/foo/settings`. deis-runtime passes the pattern's index in the manifest;
/// deis-build has no manifest yet and passes `0`, breaking the tie on the
/// pattern text instead (see [`sort_by_specificity`]). Those two agree because
/// the manifest is written in exactly the order deis-build sorted into, so the
/// tied pattern deis-build put first is also the one with the lower index.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Specificity {
    /// 0 for a pattern with no catch-all, 1 for one with a catch-all.
    catch_all: u8,
    /// Per-segment ranks, most significant first.
    ranks: Vec<u8>,
    /// Tie-breaker supplied by the caller, compared last.
    order: usize,
}

impl Specificity {
    pub fn of(pattern: &str, order: usize) -> Self {
        let parts = segments(pattern);
        let mut catch_all = 0;
        let ranks = parts
            .iter()
            .map(|part| {
                if *part == CATCH_ALL_SEGMENT {
                    catch_all = 1;
                    RANK_CATCH_ALL
                } else if part.starts_with(PLACEHOLDER_PREFIX) {
                    RANK_PLACEHOLDER
                } else {
                    RANK_LITERAL
                }
            })
            .collect();
        Self {
            catch_all,
            ranks,
            order,
        }
    }
}

impl Ord for Specificity {
    fn cmp(&self, other: &Self) -> std::cmp::Ordering {
        use std::cmp::Ordering;

        // Rule 1: a catch-all is always the last resort, whatever else the
        // pattern pins down.
        match self.catch_all.cmp(&other.catch_all) {
            Ordering::Equal => {}
            ordering => return ordering,
        }

        // Rules 2 and 3: the first differing segment decides, and a pattern
        // that keeps constraining segments after the other has run out is the
        // more specific of the two. Higher rank is more specific, so the
        // comparison is reversed to keep "smaller key" meaning "wins".
        for (mine, theirs) in self.ranks.iter().zip(other.ranks.iter()) {
            match theirs.cmp(mine) {
                Ordering::Equal => {}
                ordering => return ordering,
            }
        }
        match other.ranks.len().cmp(&self.ranks.len()) {
            Ordering::Equal => {}
            ordering => return ordering,
        }

        // Rule 4.
        self.order.cmp(&other.order)
    }
}

impl PartialOrd for Specificity {
    fn partial_cmp(&self, other: &Self) -> Option<std::cmp::Ordering> {
        Some(self.cmp(other))
    }
}

/// Order a route table most-specific first, in place.
///
/// This is the build-time half of the rule: the caller has a list of handlers
/// in whatever order a directory walk produced, and needs the order a
/// first-match-wins table has to be in.
///
/// Ties are broken on the pattern text rather than on the order the routes
/// arrived in, because a directory walk lists files differently on different
/// machines and a bundle is content-addressed - a table that reorders itself
/// would change the identity of a build whose input never changed.
pub fn sort_by_specificity<T>(routes: &mut [T], pattern_of: impl Fn(&T) -> &str) {
    routes.sort_by(|a, b| {
        let (left, right) = (pattern_of(a), pattern_of(b));
        Specificity::of(left, 0)
            .cmp(&Specificity::of(right, 0))
            .then_with(|| left.cmp(right))
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ordered(patterns: &[&str]) -> Vec<String> {
        let mut routes: Vec<String> = patterns.iter().map(|p| p.to_string()).collect();
        sort_by_specificity(&mut routes, |p| p.as_str());
        routes
    }

    /// The pattern a request-time matcher would pick, given the table in the
    /// order `sort_by_specificity` produced: the minimum key, with `order`
    /// being the position in that table. Both halves of the rule have to name
    /// the same pattern, and this is the check that they do.
    fn best(table: &[String], candidates: &[&str]) -> String {
        candidates
            .iter()
            .map(|pattern| {
                let index = table.iter().position(|p| p == pattern).expect("in table");
                (Specificity::of(pattern, index), pattern.to_string())
            })
            .min_by(|a, b| a.0.cmp(&b.0))
            .expect("at least one candidate")
            .1
    }

    #[test]
    fn a_literal_beats_a_placeholder_in_the_same_position() {
        assert_eq!(
            ordered(&["/users/:id", "/users/new"]),
            ["/users/new", "/users/:id"]
        );
    }

    #[test]
    fn the_leftmost_literal_decides_not_the_count_of_placeholders() {
        // Both patterns have one placeholder and two segments, and both match
        // `/admin/settings`. Counting placeholders leaves them tied and hands
        // the decision to whatever the tie-breaker is; the segment-by-segment
        // rule says the literal `admin` in position 1 wins outright.
        assert_eq!(
            ordered(&["/:org/settings", "/admin/:page"]),
            ["/admin/:page", "/:org/settings"]
        );
    }

    #[test]
    fn a_catch_all_is_the_last_resort_however_long_it_is() {
        assert_eq!(
            ordered(&["/api/deep/*", "/:anything"]),
            ["/:anything", "/api/deep/*"]
        );
    }

    #[test]
    fn a_longer_pattern_beats_a_shorter_one_it_agrees_with() {
        assert_eq!(ordered(&["/*", "/api/*"]), ["/api/*", "/*"]);
        assert_eq!(ordered(&["/:id", "/users/:id"]), ["/users/:id", "/:id"]);
    }

    #[test]
    fn the_order_the_routes_arrived_in_does_not_change_the_table() {
        let forward = ordered(&["/", "/a", "/b/:id", "/*"]);
        let backward = ordered(&["/*", "/b/:id", "/a", "/"]);
        assert_eq!(forward, backward);
    }

    #[test]
    fn two_patterns_of_the_same_shape_are_ordered_by_text_not_by_arrival() {
        assert_eq!(
            ordered(&["/:user/settings", "/:org/settings"]),
            ["/:org/settings", "/:user/settings"]
        );
    }

    #[test]
    fn the_first_matching_row_of_the_table_is_the_row_the_key_picks() {
        // The build-time half takes the first row that fits; the request-time
        // half takes the smallest key. This is the property that makes the two
        // the same decision, for every case above where more than one pattern
        // fits one path.
        let table = ordered(&["/:org/settings", "/admin/:page", "/admin/*", "/*"]);
        assert_eq!(
            best(
                &table,
                &["/:org/settings", "/admin/:page", "/admin/*", "/*"]
            ),
            table[0],
            "table: {table:?}"
        );
        let table = ordered(&["/:user/settings", "/:org/settings"]);
        assert_eq!(
            best(&table, &["/:user/settings", "/:org/settings"]),
            table[0]
        );
    }
}
