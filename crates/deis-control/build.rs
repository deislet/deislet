fn main() -> Result<(), Box<dyn std::error::Error>> {
    // The dashboard is embedded from `web/dist`, and that directory is a build
    // product of `web/` - `npm run build` writes it, git does not carry it.
    //
    // A binary built without it still compiles, serves the whole API, and
    // answers 404 for the dashboard pages - which is what
    // `src/api/static_files.rs` already says happens. Creating the directory
    // here keeps that the shape of the failure; an existing directory is left
    // exactly as it is, so a real build is never overwritten.
    let dist = std::path::Path::new("web/dist");
    if !dist.exists() {
        std::fs::create_dir_all(dist)?;
        println!(
            "cargo:warning=crates/deis-control/web/dist was missing, so this binary has no \
             dashboard: the API works and the dashboard pages answer 404. Run `npm install && \
             npm run build` in crates/deis-control/web and rebuild to include it."
        );
    }
    embed_web_assets(dist)?;

    // The deis-runtime protos are the single source of truth and live in the
    // deis-runtime crate. The client side is what this binary uses.
    //
    // Two services are dialled from the control plane: management (deployment
    // delivery, status, health) and trigger (cron fires a scheduled event on
    // one chosen node).
    //
    // The server side is generated too, and nothing outside `#[cfg(test)]`
    // touches it: the tests that check which credential this control plane
    // presents to a node need a node that records what it was handed, and a
    // stand-in built from the same proto is the only one whose answer means
    // anything.
    tonic_build::configure()
        .build_server(true)
        .build_client(true)
        .compile_protos_with_config(
            protobuf_config()?,
            &[
                "../deis-runtime/proto/management.proto",
                "../deis-runtime/proto/trigger.proto",
            ],
            &["../deis-runtime/proto"],
        )?;

    println!("cargo:rerun-if-changed=../deis-runtime/proto/management.proto");
    println!("cargo:rerun-if-changed=../deis-runtime/proto/trigger.proto");
    Ok(())
}

fn protobuf_config() -> Result<prost_build::Config, Box<dyn std::error::Error>> {
    let mut config = prost_build::Config::new();
    config.protoc_executable(protoc_bin_vendored::protoc_bin_path()?);
    Ok(config)
}

/// Writes `$OUT_DIR/web_assets.rs`: one `include_bytes!` per file under
/// `web/dist`, by absolute path, sorted by the path it is served at.
///
/// This used to be `#[derive(rust_embed::Embed)]`, and that macro lists the
/// directory while it expands. Under sccache-dist the expansion runs on a
/// build worker, which is handed the files rustc's dep-info names and nothing
/// else; `web/dist` is not among them, so the macro failed with "folder ...
/// does not exist" and every build of this crate had to turn distribution
/// off. Listing the directory here, on the machine that owns the checkout,
/// leaves rustc with ordinary `include_bytes!` inputs: dep-info names each
/// file, sccache ships them to the worker, and the cache key covers their
/// contents.
///
/// Every file and directory is a rerun trigger, so a new `npm run build`
/// (new hashed names, hence a changed `assets/` listing) or a deleted
/// `web/dist` reruns this script, which recreates the directory empty.
fn embed_web_assets(dist: &std::path::Path) -> Result<(), Box<dyn std::error::Error>> {
    fn walk(
        dir: &std::path::Path,
        prefix: &str,
        files: &mut Vec<(String, std::path::PathBuf)>,
    ) -> std::io::Result<()> {
        println!("cargo:rerun-if-changed={}", dir.display());
        for entry in std::fs::read_dir(dir)? {
            let entry = entry?;
            let path = entry.path();
            let name = entry.file_name().to_string_lossy().into_owned();
            let served = format!("{prefix}{name}");
            // `metadata` follows symlinks, as the old embed did.
            let metadata = std::fs::metadata(&path)?;
            if metadata.is_dir() {
                walk(&path, &format!("{served}/"), files)?;
            } else if metadata.is_file() {
                println!("cargo:rerun-if-changed={}", path.display());
                files.push((served, std::fs::canonicalize(&path)?));
            }
        }
        Ok(())
    }

    let mut files = Vec::new();
    walk(dist, "", &mut files)?;
    files.sort();

    let mut out = String::from(
        "// Generated by crates/deis-control/build.rs from web/dist. Sorted by path.\n\
         pub(crate) static WEB_ASSETS: &[(&str, &[u8])] = &[\n",
    );
    for (served, path) in &files {
        let path = path
            .to_str()
            .ok_or_else(|| format!("web/dist path is not UTF-8: {}", path.display()))?;
        out.push_str(&format!("    ({served:?}, include_bytes!({path:?})),\n"));
    }
    out.push_str("];\n");

    let out_dir = std::path::PathBuf::from(std::env::var("OUT_DIR")?);
    std::fs::write(out_dir.join("web_assets.rs"), out)?;
    Ok(())
}
